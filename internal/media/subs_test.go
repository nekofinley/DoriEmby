// Automatic subtitle selection decides what a viewer sees without touching
// anything, so it has to prefer what they can actually read.
func TestPickDefaultSubtitle(t *testing.T) {
	sub := func(id int64, lang, title string) models.Subtitle {
		return models.Subtitle{ID: id, Lang: lang, Title: title, Convertible: true}
	}
	cases := []struct {
		name string
		subs []models.Subtitle
		want int64
	}{
		{"nothing to pick", nil, 0},
		{"only one", []models.Subtitle{sub(7, "eng", "English")}, 7},
		{
			"Chinese beats English regardless of order",
			[]models.Subtitle{sub(1, "eng", "English"), sub(2, "chi", "Chinese")},
			2,
		},
		{
			"Chinese beats Cantonese",
			[]models.Subtitle{sub(1, "yue", "粵語"), sub(2, "chi", "中文")},
			2,
		},
		{
			"Simplified beats Traditional, which share an ISO code",
			[]models.Subtitle{sub(1, "chi", "繁體"), sub(2, "chi", "简体")},
			2,
		},
		{
			// The common anime-mux shape: language tags are absent, the title says it.
			"title hints work when the language tag is missing",
			[]models.Subtitle{sub(1, "", "繁日"), sub(2, "", "简日")},
			2,
		},
		{
			"chs beats cht in the title",
			[]models.Subtitle{sub(1, "", "xxx.cht"), sub(2, "", "xxx.chs")},
			2,
		},
		{
			"an identified language beats an untagged track",
			[]models.Subtitle{sub(1, "", "subs"), sub(2, "jpn", "日本語")},
			2,
		},
		{
			"ties fall back to registration order",
			[]models.Subtitle{sub(3, "chi", "简体"), sub(4, "chi", "简体")},
			3,
		},
		{
			"Chinese still wins when it is listed last",
			[]models.Subtitle{
				sub(1, "jpn", "日本語"), sub(2, "eng", "English"), sub(3, "", "简中"),
			},
			3,
		},
	}
	for _, c := range cases {
		if got := PickDefaultSubtitle(c.subs); got != c.want {
			t.Errorf("%s: PickDefaultSubtitle = %d, want %d", c.name, got, c.want)
		}
	}
}

// An untagged Simplified track must still beat an untagged Traditional one.
func TestPickDefaultSubtitleUntaggedScript(t *testing.T) {
	subs := []models.Subtitle{
		{ID: 1, Title: "繁體中文", Convertible: true},
		{ID: 2, Title: "简体中文", Convertible: true},
	}
	if got := PickDefaultSubtitle(subs); got != 2 {
		t.Fatalf("PickDefaultSubtitle = %d, want 2 (Simplified)", got)
	}
}

// "und" means the container does not know; it must not outrank a real language,
// and the title should still be able to identify the track.
func TestSubtitleRankTreatsUndAsUntagged(t *testing.T) {
	und := subtitleRank(models.Subtitle{Lang: "und", Title: "简日"})
	chi := subtitleRank(models.Subtitle{Lang: "chi", Title: "简日"})
	jpn := subtitleRank(models.Subtitle{Lang: "jpn", Title: "日本語"})
	if und[0] != chi[0] {
		t.Errorf("und (%v) should rank like its title says, chi is %v", und, chi)
	}
	if und[0] >= jpn[0] {
		t.Errorf("a track whose title says Chinese (%v) must beat Japanese (%v)", und, jpn)
	}
}

// A release can put the language where the extension would be, leaving the file
// with none at all: VCB-Studio ships "…[x265_flac_aac].Chs" and "….Cht" beside
// the video. Read by extension alone, those two tracks do not exist — which is
// how a season with Simplified *and* Traditional subtitles ends up offering only
// the Japanese track.
func TestDetectTaggedSubFormatFindsExtensionlessSubtitles(t *testing.T) {
	const vcb = "[Kamigami and VCB-Studio] Yahari Ore no Seishun Lovecome wa Machigatte Iru. [01][Ma10p_1080p][x265_flac_aac]"

	cases := []struct {
		name       string
		wantFormat string
	}{
		{vcb + ".Chs", "ass"},
		{vcb + ".Cht", "ass"},
		{vcb + ".chs", "ass"},
		{vcb + ".BIG5", "ass"},
		{vcb + ".Jap", "ass"},
		{vcb + ".简体", "ass"},
		{vcb + ".繁體", "ass"},
		{vcb + ".Eng", "ass"},
		// An extension decides the format; the tag on it is only a language hint.
		{vcb + ".Jap.ass", ""},
		{vcb + ".Chs.srt", ""},
		{vcb + ".Chs.vtt", ""},
		// Not subtitles: the video, a font archive, and a name with no tag.
		{vcb + ".mkv", ""},
		{vcb + "[Fonts].7z", ""},
		{vcb, ""},
		{"Show.S01E01", ""},
		{"Show.S01E01.1", ""},
	}
	for _, c := range cases {
		got, conv := DetectTaggedSubFormat(c.name)
		if got != c.wantFormat {
			t.Errorf("DetectTaggedSubFormat(%q) format = %q, want %q", c.name, got, c.wantFormat)
			continue
		}
		if c.wantFormat != "" && !conv {
			t.Errorf("DetectTaggedSubFormat(%q) is a text subtitle, so it must be convertible", c.name)
		}
	}
}

// The language tag says which track it is, never what it is written in, so the
// file's own bytes have the final say. Getting this wrong is worse than missing
// the track: SRT text through the ASS converter loses everything, and ASS text
// through the SRT converter comes out as its own markup.
func TestSniffTextSubFormat(t *testing.T) {
	ass := "\uFEFF[Script Info]\r\n; Script generated by Aegisub 2.1.9\r\n" +
		"ScriptType: v4.00+\r\n[V4+ Styles]\r\nStyle: Default,Arial\r\n[Events]\r\n" +
		"Dialogue: 0,0:00:01.00,0:00:03.00,Default,,0,0,0,,你好\r\n"
	srt := "1\r\n00:00:01,000 --> 00:00:03,000\r\n你好\r\n\r\n2\r\n00:00:04,000 --> 00:00:06,000\r\n再见\r\n"
	vtt := "WEBVTT\n\n00:00:01.000 --> 00:00:03.000\n你好\n"

	cases := []struct {
		name string
		data string
		want string
	}{
		{"ASS with a BOM", ass, "ass"},
		{"ASS without a BOM", strings.TrimPrefix(ass, "\uFEFF"), "ass"},
		{"SubRip", srt, "subrip"},
		{"WebVTT", vtt, "webvtt"},
		// The heading does not have to be the very first line.
		{"ASS with a leading blank line", "\n\n" + strings.TrimPrefix(ass, "\uFEFF"), "ass"},
		// Nothing recognisable must not be claimed as ASS: the SubRip converter
		// degrades to showing the text, the ASS one does not.
		{"unknown text", "just some prose\nand nothing else\n", "subrip"},
		{"empty", "", "subrip"},
	}
	for _, c := range cases {
		got, conv := SniffTextSubFormat([]byte(c.data))
		if got != c.want {
			t.Errorf("%s: SniffTextSubFormat = %q, want %q", c.name, got, c.want)
		}
		if !conv {
			t.Errorf("%s: a text subtitle must be convertible", c.name)
		}
	}
}

// A subtitle's label is what a viewer picks a track by, so it has to say which
// track it is and nothing else. Release furniture — group tags, episode numbers,
// codecs, CRCs — is most of a real sidecar's name, and leaving it in produces a
// wall of brackets that two different tracks of the same episode share.
func TestSubLabelNamesTheTrack(t *testing.T) {
	const s1 = "[Kamigami and VCB-Studio] Yahari Ore no Seishun Lovecome wa Machigatte Iru. [01][Ma10p_1080p][x265_flac_aac]"
	const s2 = "[VCB-Studio][Yahari_Ore_no_Seishun_Lovecome_wa_Machigatte_Iru._Zoku][01][x265_aac][BDrip_1080P][DED1CA06]"

	// Whatever else a label is, it must start with the script the viewer is
	// choosing between — that is the whole reason they opened the list.
	for _, c := range []struct{ name, wantPrefix string }{
		{s1 + ".Chs", "简体"},
		{s1 + ".Cht", "繁体"},
		{s1 + ".Jap.ass", "日语"},
		{s2 + ".SumiSora.tc.ass", "繁体"},
		{"/a/b/Show.S01E01.简体", "简体"},
		{"/a/b/Show.S01E01.chs.ass", "简体"},
		// The tag can sit further back when a group signs the file.
		{"Kekkai Sensen [01][x265_flac].Chs.Kamigami.ass", "简体"},
		{"Kekkai Sensen [01][x265_flac].Cht.Kamigami.ass", "繁体"},
	} {
		if got := SubLabel(c.name); !strings.HasPrefix(got, c.wantPrefix) {
			t.Errorf("SubLabel(%q) = %q, want it to start with %q", c.name, got, c.wantPrefix)
		}
	}

	// Two tracks of one episode must never share a label.
	for _, pair := range [][2]string{
		{s1 + ".Chs", s1 + ".Cht"},
		{"Kekkai Sensen [01][x265_flac].Chs.Kamigami.ass", "Kekkai Sensen [01][x265_flac].Cht.Kamigami.ass"},
	} {
		if a, b := SubLabel(pair[0]), SubLabel(pair[1]); a == b {
			t.Errorf("two tracks share the label %q — the viewer cannot choose", a)
		}
	}

	// No brackets, CRCs or codec noise survive into a label.
	for _, name := range []string{s1 + ".Chs", s2 + ".SumiSora.tc.ass"} {
		got := SubLabel(name)
		for _, junk := range []string{"[", "]", "VCB", "x265", "aac", "1080p", "BDrip", "DED1CA06", "Ma10p"} {
			if strings.Contains(got, junk) {
				t.Errorf("SubLabel(%q) = %q, still carries %q", name, got, junk)
			}
		}
	}

	// A readable name is kept, and stays bounded.
	if got := SubLabel("Show Name S01E02.chs.ass"); got != "简体 · Show Name S01E02" {
		t.Errorf("SubLabel readable name = %q", got)
	}
	if got := SubLabel("A Very Long Show Title That Runs On And On And On Forever S01E01.ass"); len([]rune(got)) > 41 {
		t.Errorf("SubLabel did not bound the label: %q (%d runes)", got, len([]rune(got)))
	}

	// A name with no tag is still cleaned up rather than shown raw...
	if got := SubLabel("/a/b/Show.S01E01.srt"); got != "Show S01E01" {
		t.Errorf("SubLabel(no tag) = %q, want %q", got, "Show S01E01")
	}
	// ...but a name is never invented for one that carries nothing at all.
	if got := SubLabel("..."); got != "..." {
		t.Errorf("SubLabel(contentless) = %q, want the name unchanged", got)
	}
}

// Regression: Go's \b is an ASCII word boundary, so `\b简\b` never matched —
// Chinese markers in ordinary names like "xxx.简日.ass" were invisible.
func TestGuessLangFindsCJKMarkers(t *testing.T) {
	cases := map[string]string{
		"Show S01E01.简日.ass":  "chi",
		"Show S01E01.繁日.ass":  "chi",
		"Show S01E01.简体.srt":  "chi",
		"Show S01E01.繁体.srt":  "chi",
		"Show S01E01.中字.srt":  "chi",
		"Show S01E01.cht.srt": "chi",
		"Show S01E01.chs.srt": "chi",
		"Show S01E01.eng.srt": "eng",
		"Show S01E01.日语.ass":  "jpn",
		"Show S01E01.粤语.srt":  "yue",
		"Show.S01E01.unknown": "",
	}
	for name, want := range cases {
		if got := GuessLang(name); got != want {
			t.Errorf("GuessLang(%q) = %q, want %q", name, got, want)
		}
	}
}

// A rendition's cues must be timed against the stream the player is on, which
// begins where a packaging session began — not against the file.
func TestShiftVTT(t *testing.T) {
	in := "WEBVTT\n\nNOTE something\n\n1\n00:00:00.500 --> 00:00:02.000 align:middle\nhello\n\n" +
		"00:00:10.000 --> 00:00:12.500\nworld\nline two\n"

	got := string(ShiftVTT([]byte(in), 0.25))
	// 0.500 - 0.25 = 0.250, and the trailing settings must survive verbatim.
	if !strings.Contains(got, "00:00:00.250 --> 00:00:01.750 align:middle") {
		t.Errorf("first cue not shifted with its settings intact:\n%s", got)
	}
	if !strings.Contains(got, "00:00:09.750 --> 00:00:12.250") {
		t.Errorf("second cue not shifted:\n%s", got)
	}
	if !strings.Contains(got, "NOTE something") || !strings.Contains(got, "WEBVTT") {
		t.Errorf("header blocks must pass through:\n%s", got)
	}
	if !strings.Contains(got, "world\nline two") {
		t.Errorf("a surviving cue's payload must stay with it:\n%s", got)
	}

	// A cue that ended before the stream began is dropped, payload and all.
	got = string(ShiftVTT([]byte(in), 5))
	if strings.Contains(got, "hello") {
		t.Errorf("a cue wholly before the offset must be dropped:\n%s", got)
	}
	if !strings.Contains(got, "00:00:05.000 --> 00:00:07.500") {
		t.Errorf("the later cue must be shifted:\n%s", got)
	}

	// A cue straddling the offset is clamped rather than dropped.
	got = string(ShiftVTT([]byte(in), 1))
	if !strings.Contains(got, "00:00:00.000 --> 00:00:01.000") {
		t.Errorf("a straddling cue must be clamped to zero:\n%s", got)
	}

	// Rounding must not produce an impossible ":60.000" timestamp.
	got = string(ShiftVTT([]byte("WEBVTT\n\n00:01:00.000 --> 00:01:01.000\nx\n"), 0.0004))
	if strings.Contains(got, ":60.000") {
		t.Errorf("rounding produced a 60-second component:\n%s", got)
	}

	// No offset is a no-op, and the input is never mutated.
	orig := []byte(in)
	if out := ShiftVTT(orig, 0); string(out) != in {
		t.Error("a zero offset must return the document unchanged")
	}
	if string(orig) != in {
		t.Error("ShiftVTT must not modify its input")
	}
}
